    time_to_onboard_days INTEGER,
    no_show_count INTEGER,
    is_redeployed BOOLEAN,
    documents JSONB,
    messages JSONB,
    reliability_score INTEGER,
    attendance_rate INTEGER,
    punctuality_rate INTEGER,
    completion_rate INTEGER,
    client_rating_class TEXT
