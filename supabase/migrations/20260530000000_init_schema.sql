    id TEXT PRIMARY KEY,
    business_name TEXT,
    vertical TEXT,
    category TEXT,
    block_type TEXT,
    start_window TEXT,
    location TEXT,
    required_skills JSONB,
    status TEXT,
    payout NUMERIC,
    charge NUMERIC,
    created_at TIMESTAMPTZ,
    checklist JSONB,
    headcount INTEGER,
    bill_rate NUMERIC,
    pay_rate NUMERIC,
    markup NUMERIC,
    hours_per_shift NUMERIC,
    duration_shifts INTEGER,
    location_name TEXT,
    shift_start_time TEXT,
    shift_end_time TEXT,
    recruiter_id TEXT,
    recruiter_name TEXT,
    branch_name TEXT,
    state_code TEXT,
    invoice_term_days INTEGER
