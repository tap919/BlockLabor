describe('FinancialData Model', () => {
  beforeEach(() => {
    jest.clearAllMocks();
  });

  test('should cache financial data', async () => {
    const data = mockFinancialData();
    mockDb.financialData.create.mockResolvedValue(data);

    const result = await mockDb.financialData.create({
      data: {
        symbol: 'AAPL',
        dataType: 'price',
        source: 'alpha_vantage',
        data: '{"price": 150.00}',
        expiresAt: new Date(Date.now() + 3600000),
      },
    });

    expect(result.symbol).toBe('AAPL');
    expect(result.dataType).toBe('price');
  });

  test('should check expiration', async () => {
    const data = mockFinancialData({
      fetchedAt: new Date(Date.now() - 7200000).toISOString(),
      expiresAt: new Date(Date.now() - 3600000).toISOString(),
    });
    mockDb.financialData.findFirst.mockResolvedValue(data);

    const result = await mockDb.financialData.findFirst({
      where: {
        symbol: 'AAPL',
        dataType: 'price',
      },
    });

    const isExpired = result && new Date(result.expiresAt) < new Date();
    expect(isExpired).toBe(true);
  });

  test('should enforce unique symbol-type-source', async () => {
    mockDb.financialData.upsert.mockResolvedValue(mockFinancialData());

    await mockDb.financialData.upsert({
      where: {
        symbol_dataType_source: {
          symbol: 'AAPL',
          dataType: 'price',
          source: 'alpha_vantage',
        },
      },
      update: { data: '{"price": 155.00}' },
      create: {
        symbol: 'AAPL',
        dataType: 'price',
        source: 'alpha_vantage',
        data: '{"price": 155.00}',
        expiresAt: new Date(Date.now() + 3600000),
      },
    });

    expect(mockDb.financialData.upsert).toHaveBeenCalled();
  });
});

