// ============================================
// Project Model Tests
// ============================================
describe('Project Model', () => {
  beforeEach(() => {
    jest.clearAllMocks();
  });

  describe('Create Operations', () => {
    test('should create project with required fields', async () => {
      const project = mockProject();
      mockDb.project.create.mockResolvedValue(project);

      const result = await mockDb.project.create({
        data: {
          name: 'Test Project',
          status: 'draft',
          mode: 'simulation',
        },
      });

      expect(result.name).toBe('Test Project');
      expect(mockDb.project.create).toHaveBeenCalled();
    });

    test('should create project with all optional fields', async () => {
      const project = mockProject({
        description: 'Full description',
        createdBy: 'user_123',
        startedAt: new Date().toISOString(),
      });

      mockDb.project.create.mockResolvedValue(project);

      const result = await mockDb.project.create({
        data: {
          name: 'Test Project',
          description: 'Full description',
          status: 'running',
          mode: 'live',
          createdBy: 'user_123',
        },
      });

      expect(result.description).toBe('Full description');
    });

    test('should auto-generate project ID', async () => {
      const project = mockProject();
      mockDb.project.create.mockResolvedValue(project);

      await mockDb.project.create({
        data: { name: 'Test' },
      });

      // ID should be generated by Prisma
      expect(mockDb.project.create).toHaveBeenCalled();
    });

    test('should set timestamps automatically', async () => {
      const now = new Date();
      const project = mockProject({
        createdAt: now.toISOString(),
        updatedAt: now.toISOString(),
      });

      mockDb.project.create.mockResolvedValue(project);

      const result = await mockDb.project.create({
        data: { name: 'Test' },
      });

      expect(result.createdAt).toBeDefined();
      expect(result.updatedAt).toBeDefined();
    });
  });

  describe('Read Operations', () => {
    test('should find project by ID', async () => {
      const project = mockProject();
      mockDb.project.findUnique.mockResolvedValue(project);

      const result = await mockDb.project.findUnique({
        where: { id: 'project_test' },
      });

      expect(result).not.toBeNull();
    });

    test('should return null for non-existent project', async () => {
      mockDb.project.findUnique.mockResolvedValue(null);

      const result = await mockDb.project.findUnique({
        where: { id: 'nonexistent' },
      });

      expect(result).toBeNull();
    });

    test('should find many projects', async () => {
      const projects = [mockProject(), mockProject({ id: 'project_2' })];
      mockDb.project.findMany.mockResolvedValue(projects);

      const result = await mockDb.project.findMany();

      expect(result).toHaveLength(2);
    });

    test('should include related phases', async () => {
      const project = {
        ...mockProject(),
        phases: [mockPhase(), mockPhase({ id: 'phase_2' })],
      };

      mockDb.project.findUnique.mockResolvedValue(project);

      const result = await mockDb.project.findUnique({
        where: { id: 'project_test' },
        include: { phases: true },
      });

      expect(result?.phases).toHaveLength(2);
    });

    test('should include portfolio with positions', async () => {
      const project = {
        ...mockProject(),
        portfolio: {
          ...mockPortfolio(),
          positions: [mockPosition(), mockPosition({ id: 'position_2' })],
        },
      };

      mockDb.project.findUnique.mockResolvedValue(project);

      const result = await mockDb.project.findUnique({
        where: { id: 'project_test' },
        include: { portfolio: { include: { positions: true } } },
      });

      expect(result?.portfolio?.positions).toHaveLength(2);
    });

    test('should filter by status', async () => {
      const runningProjects = [mockProject({ status: 'running' })];
      mockDb.project.findMany.mockResolvedValue(runningProjects);

      await mockDb.project.findMany({
        where: { status: 'running' },
      });

      expect(mockDb.project.findMany).toHaveBeenCalledWith(
        expect.objectContaining({
          where: { status: 'running' },
        })
      );
    });

    test('should order by creation date', async () => {
      mockDb.project.findMany.mockResolvedValue([]);

      await mockDb.project.findMany({
        orderBy: { createdAt: 'desc' },
      });

      expect(mockDb.project.findMany).toHaveBeenCalledWith(
        expect.objectContaining({
          orderBy: { createdAt: 'desc' },
        })
      );
    });
  });

  describe('Update Operations', () => {
    test('should update project status', async () => {
      const updated = mockProject({ status: 'running' });
      mockDb.project.update.mockResolvedValue(updated);

      const result = await mockDb.project.update({
        where: { id: 'project_test' },
        data: { status: 'running' },
      });

      expect(result.status).toBe('running');
    });

    test('should update project timestamps', async () => {
      const startedAt = new Date().toISOString();
      const updated = mockProject({ status: 'running', startedAt });
      mockDb.project.update.mockResolvedValue(updated);

      await mockDb.project.update({
        where: { id: 'project_test' },
        data: { 
          status: 'running',
          startedAt: new Date(startedAt),
        },
      });

      expect(mockDb.project.update).toHaveBeenCalled();
    });

    test('should complete project', async () => {
      const completedAt = new Date().toISOString();
      const updated = mockProject({ 
        status: 'completed', 
        completedAt 
      });
      mockDb.project.update.mockResolvedValue(updated);

      const result = await mockDb.project.update({
        where: { id: 'project_test' },
        data: { 
          status: 'completed',
          completedAt: new Date(completedAt),
        },
      });

      expect(result.status).toBe('completed');
    });
  });

  describe('Delete Operations', () => {
    test('should delete project', async () => {
      mockDb.project.delete.mockResolvedValue(mockProject());

      await mockDb.project.delete({
        where: { id: 'project_test' },
      });

      expect(mockDb.project.delete).toHaveBeenCalled();
    });

    test('should cascade delete phases', async () => {
      // Prisma handles cascade via schema
      mockDb.project.delete.mockResolvedValue(mockProject());

      await mockDb.project.delete({
        where: { id: 'project_test' },
      });

      // Phases should be deleted via cascade
      expect(mockDb.project.delete).toHaveBeenCalled();
    });
  });

  describe('Count Operations', () => {
    test('should count total projects', async () => {
      mockDb.project.count.mockResolvedValue(10);

      const count = await mockDb.project.count();

      expect(count).toBe(10);
    });

    test('should count by status', async () => {
      mockDb.project.count.mockResolvedValue(3);

      const count = await mockDb.project.count({
        where: { status: 'running' },
      });

      expect(count).toBe(3);
    });
  });
});

